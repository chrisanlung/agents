COMMENT ON COLUMN therapist.photo_key IS
    'Opaque storage key produced by Storage.Upload() (ADR 0011 §2.1). '
    'Format: "therapists/{therapist_id}/{16-hex}.{ext}". '
    'Never contains scheme or host — controllers call Storage.URL(ctx, key) '
    'at read time to resolve to a public URL. '
    'NULL = no photo uploaded yet.';

COMMENT ON COLUMN therapist.height_cm IS
    'Therapist height in whole centimetres. Customer-visible in Phase 5 '
    'booking picker. Valid range 100–250. Placeholder rows from migration '
    '000020 carry the value 160; admin UI flags these for curation.';

COMMENT ON COLUMN therapist.weight_kg IS
    'Therapist weight in whole kilograms. Customer-visible in Phase 5 '
    'booking picker. Valid range 30–250. Placeholder rows from migration '
    '000020 carry the value 60; admin UI flags these for curation.';

COMMENT ON COLUMN therapist.build IS
    'Body build category. Customer-visible in Phase 5 booking picker. '
    'Controlled vocabulary: langsing | sedang | atletis | tegap. '
    'Stored as TEXT + CHECK (not a native ENUM) so adding values in future '
    'migrations does not require ALTER TYPE.';
