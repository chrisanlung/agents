-- ---------------------------------------------------------------------------
-- STEP 1: Drop the old inline CHECK on photo_url before renaming.
--
-- Migration 000003 defined the column as:
--   photo_url TEXT NULL CHECK (photo_url IS NULL OR char_length(photo_url) <= 2048)
-- PostgreSQL auto-names an anonymous inline CHECK constraint as
-- <table>_<column>_check — i.e. therapist_photo_url_check.
-- We must drop it now; after the RENAME it would reference a non-existent
-- column name and cannot be dropped by the old name.
-- ---------------------------------------------------------------------------
ALTER TABLE therapist
    DROP CONSTRAINT IF EXISTS therapist_photo_url_check;

-- ---------------------------------------------------------------------------
-- STEP 2: Rename photo_url → photo_key.
--
-- RENAME preserves any B-tree indexes on the column and adjusts their
-- internal column references automatically. There are no named indexes on
-- photo_url in migrations 000003–000019, so this is clean.
-- ---------------------------------------------------------------------------
ALTER TABLE therapist
    RENAME COLUMN photo_url TO photo_key;

-- ---------------------------------------------------------------------------
-- STEP 3: Null out stranded full-URL values.
--
-- Any existing photo_url value is a full HTTP(S) URL (e.g.
-- "https://…/uploads/…"). These are not opaque storage keys and cannot be
-- resolved by Storage.URL(). Null them so the column is in a known-clean
-- state. Admins re-upload via the new POST …/therapists/:id/photo endpoint.
-- Affects only dev-seed rows in acme-spa (ADR 0011 §2.3.1).
-- ---------------------------------------------------------------------------
UPDATE therapist
    SET photo_key = NULL
    WHERE photo_key IS NOT NULL;

-- ---------------------------------------------------------------------------
-- STEP 4: Add length constraint for key semantics (≤ 512 chars).
--
-- Storage keys generated by the upload pipeline are
-- "therapists/{uuid}/{16-hex}.{ext}" — well under 512 characters.
-- A URL-length cap (2048) would be misleading given the new semantics.
-- ---------------------------------------------------------------------------
ALTER TABLE therapist
    ADD CONSTRAINT therapist_photo_key_length
        CHECK (photo_key IS NULL OR char_length(photo_key) <= 512);

-- ---------------------------------------------------------------------------
-- STEP 5: Add height_cm.
--
-- Add as nullable first, populate existing rows with the placeholder value
-- (160 — within the valid range 100–250 so the subsequent CHECK does not
-- fail), promote to NOT NULL, add the CHECK constraint, then drop the
-- DEFAULT so new rows must supply a real value.
-- ---------------------------------------------------------------------------
ALTER TABLE therapist
    ADD COLUMN IF NOT EXISTS height_cm SMALLINT NULL DEFAULT 160;

UPDATE therapist
    SET height_cm = 160
    WHERE height_cm IS NULL;

ALTER TABLE therapist
    ALTER COLUMN height_cm SET NOT NULL;

ALTER TABLE therapist
    ADD CONSTRAINT therapist_height_cm_check
        CHECK (height_cm BETWEEN 100 AND 250);

ALTER TABLE therapist
    ALTER COLUMN height_cm DROP DEFAULT;

-- ---------------------------------------------------------------------------
-- STEP 6: Add weight_kg.
--
-- Same pattern as height_cm. Placeholder 60 is within the valid range
-- 30–250.
-- ---------------------------------------------------------------------------
ALTER TABLE therapist
    ADD COLUMN IF NOT EXISTS weight_kg SMALLINT NULL DEFAULT 60;

UPDATE therapist
    SET weight_kg = 60
    WHERE weight_kg IS NULL;

ALTER TABLE therapist
    ALTER COLUMN weight_kg SET NOT NULL;

ALTER TABLE therapist
    ADD CONSTRAINT therapist_weight_kg_check
        CHECK (weight_kg BETWEEN 30 AND 250);

ALTER TABLE therapist
    ALTER COLUMN weight_kg DROP DEFAULT;

-- ---------------------------------------------------------------------------
-- STEP 7: Add build.
--
-- Four-value controlled vocabulary. TEXT + CHECK is used in preference to a
-- native Postgres ENUM so values can be added via a non-destructive migration
-- (ALTER TABLE ... ADD CONSTRAINT with a new CHECK) rather than requiring
-- ALTER TYPE, which blocks concurrent reads in older Postgres versions.
-- Placeholder 'sedang' is the most common build category and is within the
-- allowed set, so the CHECK is immediately satisfied.
-- ---------------------------------------------------------------------------
ALTER TABLE therapist
    ADD COLUMN IF NOT EXISTS build TEXT NULL DEFAULT 'sedang';

UPDATE therapist
    SET build = 'sedang'
    WHERE build IS NULL;

ALTER TABLE therapist
    ALTER COLUMN build SET NOT NULL;

ALTER TABLE therapist
    ADD CONSTRAINT therapist_build_check
        CHECK (build IN ('langsing', 'sedang', 'atletis', 'tegap'));

ALTER TABLE therapist
    ALTER COLUMN build DROP DEFAULT;

